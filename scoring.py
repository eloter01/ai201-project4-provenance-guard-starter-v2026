"""Combine authorship signals and map scores to labels."""

from numbers import Real

import config


def _validate_signal_score(score: float, name: str) -> None:
    if isinstance(score, bool) or not isinstance(score, Real):
        raise TypeError(f"{name} must be a real number.")
    if not 0 <= score <= 1:
        raise ValueError(f"{name} must be finite and between 0 and 1.")


def combine_signals(model_score: float, style_score: float) -> float:
    """Blend two scores and require agreement at the AI cutoff.

    Args:
        model_score: Score for text predictability, from 0 to 1.
        style_score: Score for writing style, from 0 to 1.

    Returns:
        The weighted average, or the midpoint of the unsure range if the
        average reaches the AI cutoff and either score is below it.

    Raises:
        TypeError: Either score is nonnumeric or a boolean.
        ValueError: Either score is outside the finite range from 0 to 1.
    """
    _validate_signal_score(model_score, "model_score")
    _validate_signal_score(style_score, "style_score")

    average = (
        config.WEIGHT_MODEL_SIGNAL * model_score
        + config.WEIGHT_STYLE_SIGNAL * style_score
    )
    if average >= config.AI_THRESHOLD > min(model_score, style_score):
        return (config.HUMAN_THRESHOLD + config.AI_THRESHOLD) / 2
    return average


def score_to_label(score: float) -> tuple[str, str]:
    """Map a combined score to an authorship guess and reader-facing label.

    Args:
        score: Combined authorship score from 0 to 1.

    Returns:
        A pair containing the guess and the label text.

    Raises:
        TypeError: The score is nonnumeric or a boolean.
        ValueError: The score is outside the finite range from 0 to 1.
    """
    _validate_signal_score(score, "score")
    if score >= config.AI_THRESHOLD:
        return (
            "ai",
            "This text looks likely to have been generated by AI. "
            "You can submit an appeal to request a review.",
        )
    if score <= config.HUMAN_THRESHOLD:
        return (
            "human",
            "This text looks likely to have been written by a person.",
        )
    return (
        "unsure",
        "We’re unsure whether this text was written by a person or generated "
        "by AI.",
    )


def label_ranges() -> list[tuple[str, str]]:
    """List the score bounds for each label using the configured cutoffs."""
    human = config.HUMAN_THRESHOLD
    ai = config.AI_THRESHOLD
    return [
        ("high-confidence human", f"0 ≤ score ≤ {human}"),
        ("unsure", f"{human} < score < {ai}"),
        ("high-confidence AI", f"{ai} ≤ score ≤ 1"),
    ]
